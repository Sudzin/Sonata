const fs = require('fs');

let roadmap = fs.readFileSync('ROADMAP.md', 'utf8');

// Check off the easy ones
roadmap = roadmap.replace(/- \[ \] Сделать одинаковую высоту гостевого блока/, '- [x] Сделать одинаковую высоту гостевого блока');
